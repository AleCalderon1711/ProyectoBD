  [1, 2, 3, 4, 5].map((nivel) => ({
    id: `${codigoIso}-q${nivel}`,
    nivel: nivel as 1 | 2 | 3 | 4 | 5,
    texto: `Pregunta nivel ${nivel} para control ${codigoIso} (pendiente definición del documento fuente).`,
  }))

