export type RelacionImpacto = 'Alta' | 'Media' | 'Baja'

export interface PreguntaCuestionario {
  id: string
  nivel: 1 | 2 | 3 | 4 | 5
  texto: string
}

export interface ControlCuestionario {
  id: string
  codigoIso: string
  nombre: string
  dominio: 'Organizacional' | 'Personas' | 'Físico' | 'Tecnológico'
  peso: number
  relacionC: RelacionImpacto
  relacionI: RelacionImpacto
  relacionD: RelacionImpacto
  preguntas: PreguntaCuestionario[]
}

